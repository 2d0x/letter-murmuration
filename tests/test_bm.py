from pathlib import Path
from playwright.sync_api import sync_playwright
here = Path(__file__).resolve().parent.parent
bm = (here / "dist/bm/bookmarklet.txt").read_text(encoding="utf-8")
with sync_playwright() as p:
    b = p.chromium.launch(args=["--use-angle=swiftshader", "--enable-unsafe-swiftshader"])
    pg = b.new_page(viewport={"width": 1440, "height": 900})
    errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto((here / "tests" / "mock_wiki.html").resolve().as_uri())
    pg.evaluate("(h) => { const a = document.createElement('a'); a.id = 'bmtest'; a.href = h; a.textContent = 'bm'; a.style.cssText = 'position:fixed;left:0;top:0;z-index:1'; document.body.prepend(a); }", bm)
    pg.click("#bmtest"); pg.wait_for_timeout(600)
    pg.wait_for_function("window.LetterSwarm && LetterSwarm.__instance", timeout=10000)
    st = pg.evaluate("LetterSwarm.__instance.stats()")
    pg.evaluate("LetterSwarm.__instance.setMode('flock'); LetterSwarm.__instance.advance(40)")
    act = pg.evaluate("LetterSwarm.__instance.stats().active")
    pg.screenshot(path=str(here / "shots/bm_wiki.png"))
    pg.click("#bmtest", force=True); pg.wait_for_timeout(600)
    off = pg.evaluate("[!!LetterSwarm.__instance, document.querySelectorAll('canvas.ls-canvas').length, document.querySelectorAll('.ls-hidden').length]")
    pg.click("#bmtest", force=True); pg.wait_for_timeout(600)
    on2 = pg.evaluate("!!(LetterSwarm.__instance)")
    pg.keyboard.press("Escape"); pg.wait_for_timeout(100)
    off2 = pg.evaluate("!!(LetterSwarm.__instance)")
    print(f"вики: букв {st['letters']}, рендер {st['renderer']}, в полёте после 2 → {act}; второй клик выкл: {off}; третий вкл: {on2}; Esc выкл: {not off2}; ошибки: {errs}")
    pg.close()
    pg = b.new_page(viewport={"width": 1280, "height": 900})
    errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto((here / "dist/bm/index.html").resolve().as_uri()); pg.wait_for_timeout(400)
    href = pg.evaluate("document.getElementById('bm').getAttribute('href')")
    pg.screenshot(path=str(here / "shots/bm_install.png"), full_page=True)
    pg.click("#try"); pg.wait_for_timeout(200)
    st = pg.evaluate("LetterSwarm.__instance && LetterSwarm.__instance.stats()")
    pg.keyboard.press("3"); pg.evaluate("LetterSwarm.__instance.advance(60)")
    pg.screenshot(path=str(here / "shots/bm_install_run.png"))
    btn = pg.inner_text("#try")
    pg.click("#try"); off = pg.evaluate("!!LetterSwarm.__instance")
    print(f"установка: href {href[:11]}… {len(href)} симв., демо букв {st and st['letters']}, кнопка «{btn}», выкл: {not off}, ошибки: {errs}")
    b.close()
